import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {existsSync} from 'node:fs';
const url=new URL('../../../docs/shared/inference/text-norm-lowering.mjs',import.meta.url);
assert.ok(existsSync(url),'Missing bounded inner RMSNorm graph transform');
const {rewriteInnerRmsNormGraph,verifyInnerRmsNormGraph}=await import(url);
const sha=raw=>createHash('sha256').update(raw).digest('hex');
const original=Uint8Array.from([19,9,1,2,9,9,9,9,9,9,3,4,9,9,9,9,9,9,9,9]);
const expected=Uint8Array.from([22,9,10,11,12,9,9,9,9,9,9,20,21,22,23,9,9,9,9,9,9,9,9]);
const operation=(role,offset,before,after)=>({role,offset,beforeHex:Buffer.from(before).toString('hex'),afterBase64:Buffer.from(after).toString('base64')});
const recipe={schemaVersion:1,type:'umt5-inner-rmsnorm-avx2-cascade-f32-v1',status:'diagnostic-only-unaccepted',index:0,path:'block00',sourceAsset:{bytes:20,sha256:sha(original)},executedBytes:23,executedGraphSha256:sha(expected),sourceGraphPayloadOffset:1,sourceGraphLength:19,executedGraphLength:22,operations:[operation('graph-length',0,[19],[22]),operation('inner-rmsnorm-0-reduce-mean',2,[1,2],[10,11,12]),operation('inner-rmsnorm-1-reduce-mean',10,[3,4],[20,21,22,23])]};
const output=await rewriteInnerRmsNormGraph(original,recipe,{verifiedSourceAssetSha256:sha(original)});
assert.deepEqual(output,expected);assert.notEqual(output.buffer,original.buffer);
assert.deepEqual(original,Uint8Array.from([19,9,1,2,9,9,9,9,9,9,3,4,9,9,9,9,9,9,9,9]));
const result=await verifyInnerRmsNormGraph(output,recipe);
assert.equal(result.sourceAssetSha256,sha(original));assert.equal(result.executedGraphSha256,sha(expected));assert.equal(result.wholeGraphCopies,1);
await assert.rejects(rewriteInnerRmsNormGraph(original,recipe,{verifiedSourceAssetSha256:'0'.repeat(64)}),/source.*hash/i);
const corrupt=new Uint8Array(output);corrupt[corrupt.length-1]^=1;
await assert.rejects(verifyInnerRmsNormGraph(corrupt,recipe),/execution.*hash/i);
const controller=new AbortController();
await assert.rejects(rewriteInnerRmsNormGraph(original,recipe,{verifiedSourceAssetSha256:sha(original),signal:controller.signal,onProgress:()=>controller.abort(new DOMException('cancel norm copy','AbortError'))}),/cancel norm copy/);
assert.equal(original[0],19);
console.log('PASS source-preserving inner norm transform, execution hash and cancellation (NN0)');

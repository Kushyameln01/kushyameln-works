import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {runVae} from '../../../docs/shared/inference/vae.mjs';
import {encodeTensor,decodeTensor} from '../../../docs/shared/inference/tensor.mjs';
const m=JSON.parse(fs.readFileSync(new URL('./profile.json',import.meta.url)));
const bytes=new Uint8Array([1,2,3,4]),weight=new Uint8Array(1024),bias=new Uint8Array(64);
const hash=x=>createHash('sha256').update(x).digest('hex');
m.assets.decoderBody={...m.assets.decoderBody,bytes:4,sha256:hash(bytes)};
m.assets.conv2Weight={...m.assets.conv2Weight,sha256:hash(weight)};
m.assets.conv2Bias={...m.assets.conv2Bias,sha256:hash(bias)};
const frameProcessing={schemaVersion:1,policy:'wan21-causal-floor-v1',sourceFrames:8,latentFrames:2,consumedFrames:5,unusedTailFrames:3};
const tensor={dtype:'float32',layout:'NCTHW',shape:[1,16,2,2,2],meaning:'raw-posterior-mean',modelSha256:m.model.sha256,data:new Float32Array(128),frameProcessing};
let released=0;
const ort={env:{wasm:{numThreads:1}},Tensor:class{constructor(type,data,dims){Object.assign(this,{type,data,dims});}dispose(){}},InferenceSession:{create:async()=>({inputMetadata:[{name:'input',type:'float32',shape:tensor.shape}],outputMetadata:[{name:'output',type:'float32',shape:m.profile.videoShape}],run:async()=>({output:new ort.Tensor('float32',new Float32Array(3840),m.profile.videoShape)}),release:async()=>{released++;}})}};
const result=await runVae({operation:'decode',tensor,manifest:m,files:new Map([[m.assets.decoderBody.file,bytes],[m.assets.conv2Weight.file,weight],[m.assets.conv2Bias.file,bias]]),ort,hike:{matmul:(_w,x)=>new Float32Array(x),affine:x=>new Float32Array(x)}});
assert.deepEqual(result.tensor.frameProcessing,frameProcessing);
frameProcessing.sourceFrames=999;assert.equal(result.tensor.frameProcessing.sourceFrames,8);
assert.deepEqual((await decodeTensor(await encodeTensor(result.tensor))).frameProcessing,result.tensor.frameProcessing);
assert.equal(released,1);
console.log('PASS: metadata-only ORT double preserves stream source-frame accounting through compatible fixed-profile decode/save (not NN evidence)');

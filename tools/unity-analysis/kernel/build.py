#!/usr/bin/env python3
"""Build + inspect only. Never instantiate or execute the Unity WASM or tests."""
from pathlib import Path
import argparse, hashlib, json, os, re, subprocess, tarfile, time

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
DIST=ROOT/'static-src/shared/unity-analysis/kernel'
REV='fdad7bb974b208b9e8edba19af7cff1f9f9061be'
ARCHIVE='91250b9c613c26a22ab2469d55a774fade8d97a71a38f0847ace3a7dbc8d26c2'
BEFORE='fff32213b77b921f3f37432264dad00193f65874256c52aa74b96f15d0b983ac'
AFTER='99b0cb1faf774e32aa0d730ce4d81eb1814de94323c8a7a45ec67f61e9968605'
COMPILER='c4466857c3ba655807b7e9b658263128e8e23ebb62ccb6546aa3772fa6819e92'
ABI='hike-unity-i32-v1'
EXPORTS=['UaIncoming','UaTypeCheck','UaDiff']
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ['go','zig','wasm2wat','hike-archive']:parser.add_argument('--'+name,type=Path,required=True)
    args=parser.parse_args();build=HERE/'.build';DIST.mkdir(parents=True,exist_ok=True)
    for name in ['tmp','go-cache','go-path','zig-local-cache','zig-global-cache']:(build/name).mkdir(parents=True,exist_ok=True)
    env=dict(os.environ,GOCACHE=str(build/'go-cache'),GOPATH=str(build/'go-path'),TMPDIR=str(build/'tmp'),ZIG_LOCAL_CACHE_DIR=str(build/'zig-local-cache'),ZIG_GLOBAL_CACHE_DIR=str(build/'zig-global-cache'))
    commands=[]
    def run(command,cwd=None):
        command=list(map(str,command));started=time.monotonic()
        result=subprocess.run(command,cwd=cwd,env=env,capture_output=True,text=True)
        commands.append({'command':command,'seconds':round(time.monotonic()-started,4),'exitCode':result.returncode})
        if result.returncode:
            (build/'last-failure.log').write_text(result.stdout+result.stderr)
            raise RuntimeError(result.stdout+result.stderr)
        return result
    versions={'go':run([args.go,'version']).stdout.strip(),'zig':run([args.zig,'version']).stdout.strip(),'wabt':run(['node',args.wasm2wat,'--version']).stdout.strip()}
    if 'go1.22.12 ' not in versions['go'] or versions['zig']!='0.13.0' or versions['wabt']!='1.0.39':raise RuntimeError('Tool version mismatch')
    if sha(args.hike_archive)!=ARCHIVE:raise RuntimeError('Source archive mismatch')
    with tarfile.open(args.hike_archive) as source:source.extractall(build,filter='data')
    source=build/f'hike-lang-{REV}';runtime=source/'pkg/backend/llvm/runtime/runtime_wasm32.ll'
    if sha(runtime)!=BEFORE:raise RuntimeError('Unmodified runtime mismatch')
    old=b'%hash_match = icmp eq i64 %ehash, %hash';new=b'%hash_match = icmp eq i32 %ehash, %hash'
    data=runtime.read_bytes()
    if data.count(old)!=1:raise RuntimeError('Runtime correction source mismatch')
    runtime.write_bytes(data.replace(old,new))
    if sha(runtime)!=AFTER:raise RuntimeError('Corrected runtime mismatch')
    compiler=build/'hikec';run([args.go,'build','-trimpath','-buildvcs=false','-o',compiler,'./cmd/hikec'],source)
    if sha(compiler)!=COMPILER:raise RuntimeError('Compiler identity differs')
    ir=build/'unity-analysis.ll';run([compiler,'emit-ir','-target','wasm32','-o',ir,HERE/'unity-analysis.hike'])
    wasm=DIST/'unity-analysis.wasm'
    # LLVM can lower zeroing to Zig's internal memset; omit its large debug-only
    # sections from the deployment artifact. Inspect final numeric exports below.
    command=[args.zig,'cc','-target','wasm32-freestanding','-O3','-Xclang','-O3','-Xclang','-target-feature','-Xclang','-simd128','-Xclang','-vectorize-loops','-Xclang','-vectorize-slp','-nostdlib','-Wl,--no-entry','-Wl,--strip-debug','-Wl,--max-memory=0x1000000']+[f'-Wl,--export={name}' for name in EXPORTS]+[ir,'-o',wasm]
    result=run(command);(build/'link.log').write_text(result.stdout+result.stderr)
    wat=build/'unity-analysis.wat';run(['node',args.wasm2wat,wasm,'-o',wat]);text=wat.read_text()
    if '(import ' in text:raise RuntimeError('Unexpected import')
    if not re.search(r'\(memory \(;0;\) 16 256\)',text):raise RuntimeError('Memory bound changed')
    if re.search(r'\b(?:v128|i8x16|i16x8|i32x4|i64x2|f32x4|f64x2)\.',text):raise RuntimeError('Unexpected SIMD')
    actual=re.findall(r'\(export "([^"]+)"',text)
    if sorted(actual)!=sorted(['memory',*EXPORTS]):raise RuntimeError('Unexpected exports')
    for name in EXPORTS:
        export=re.search(rf'\(export "{name}" \(func (\d+)\)\)',text)
        if not export:raise RuntimeError(f'Missing function export index: {name}')
        signature=rf'\(func \(;{export.group(1)};\) \(type \d+\) \(param i32 i32 i32 i32 i32\) \(result i32\)'
        if not re.search(signature,text):raise RuntimeError(f'Unexpected signature: {name}')
    digest=sha(wasm)
    (DIST/'registry.mjs').write_text('// Generated by tools/unity-analysis/kernel/build.py.\nexport const UNITY_KERNEL=Object.freeze({'+f"key:'hike-unity-i32-v1:{digest}:scalar',variant:'scalar',abi:'{ABI}',sha256:'{digest}',url:new URL('./unity-analysis.wasm',import.meta.url).href"+'});\n')
    (DIST/'LICENSE-Hike.txt').write_bytes((source/'LICENSE').read_bytes())
    record={'status':'built-and-statically-inspected; NOT EXECUTED','hikeCommit':REV,'archiveSha256':ARCHIVE,'runtimePatch':{'beforeSha256':BEFORE,'afterSha256':AFTER,'before':old.decode(),'after':new.decode()},'compilerSha256':sha(compiler),'versions':versions,'sourceSha256':sha(HERE/'unity-analysis.hike'),'llvmSha256':sha(ir),'wasmSha256':digest,'wasmBytes':wasm.stat().st_size,'watSha256':sha(wat),'abi':ABI,'exports':{name:'(i32,i32,i32,i32,i32)->i32' for name in EXPORTS},'imports':[],'memoryPages':{'initial':16,'maximum':256},'simd':False,'commands':commands}
    (HERE/'build-record.json').write_text(json.dumps(record,indent=2)+'\n')
    print(json.dumps({key:record[key] for key in ['status','wasmBytes','wasmSha256','exports']}))
if __name__=='__main__':main()

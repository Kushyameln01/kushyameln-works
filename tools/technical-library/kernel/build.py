#!/usr/bin/env python3
"""Pinned Hike -> WABT build; toolchain is private and never published."""
import hashlib,json,os,pathlib,shutil,subprocess
HERE=pathlib.Path(__file__).resolve().parent
ROOT=HERE.parents[2]
TOOL=HERE/'.toolchain'; BUILD=HERE/'.build'; DIST=ROOT/'docs/shared/technical-library/kernel'; EVIDENCE=BUILD/'reports'
REV='3c51fde6675f317453919bd505d0e2d0f638e7f1'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def run(args,env=None):return subprocess.run(list(map(str,args)),check=True,capture_output=True,text=True,env=env).stdout.strip()
def main():
 env=dict(os.environ,PATH=str(TOOL/'node_modules/.bin')+os.pathsep+os.environ['PATH'])
 BUILD.mkdir(exist_ok=True); DIST.mkdir(parents=True,exist_ok=True); EVIDENCE.mkdir(parents=True,exist_ok=True)
 versions={'go':run([TOOL/'go/bin/go','version']),'wabt':run(['node',TOOL/'node_modules/wabt/bin/wat2wasm','--version']),'node':run(['node','--version'])}
 if 'go1.22.12 ' not in versions['go'] or versions['wabt']!='1.0.39':raise RuntimeError('Toolchain version mismatch')
 for name,source in [('probe','probe.hike'),('step','index-step.hike')]:
  d=BUILD/name;d.mkdir(exist_ok=True);shutil.copyfile(HERE/source,d/'main.hike')
  result=subprocess.run([str(TOOL/'hikec'),'build','-target','wabt','-wasm-mode','normal','-o',str(d/(name+'.wasm')),str(d/'main.hike')],env=env,capture_output=True,text=True)
  (d/'build.log').write_text(result.stdout+result.stderr)
  if result.returncode:raise RuntimeError(result.stdout+result.stderr)
 wasm=BUILD/'step/step.wasm';wat=BUILD/'step/step.wat'
 run(['node',TOOL/'node_modules/wabt/bin/wasm2wat',wasm,'-o',wat])
 text=wat.read_text()
 if '(import ' in text:raise RuntimeError('Unexpected imports')
 # Check the exported function's final WAT signature independently of source names.
 import re
 idx=re.search(r'\(export "KiStep" \(func (\d+)\)\)',text).group(1)
 if not re.search(r'\(func \(;'+idx+r';\) \(type \d+\) \(param i32 i32 i32 i32 i32 i32 i32\) \(result i32\)',text):raise RuntimeError('Wrong KiStep ABI')
 target=DIST/'index-step.wasm';shutil.copyfile(wasm,target)
 digest=sha(target)
 (DIST/'registry.mjs').write_text('// Generated by tools/technical-library/kernel/build.py.\nexport const KNOWLEDGE_KERNEL=Object.freeze({key:"knowledge-i32-v1:'+digest+':scalar",variant:"scalar",abi:"knowledge-i32-v1",sha256:"'+digest+'",url:new URL("./index-step.wasm",import.meta.url).href});\n')
 shutil.copyfile(TOOL/('hike-lang-'+REV)/'LICENSE',DIST/'LICENSE-Hike.txt')
 record={'status':'built-and-statically-inspected; execution separately recorded','hikeCommit':REV,'backend':'wabt normal','versions':versions,'compilerSha256':sha(TOOL/'hikec'),'sourceSha256':sha(HERE/'index-step.hike'),'wasmSha256':digest,'wasmBytes':target.stat().st_size,'watSha256':sha(wat),'sources':json.loads((TOOL/'sources.json').read_text()),'wabtLockSha256':sha(TOOL/'package-lock.json'),'imports':[],'signature':'KiStep(i32,i32,i32,i32,i32,i32,i32)->i32','probeWasmSha256':sha(BUILD/'probe/probe.wasm')}
 (EVIDENCE/'kernel-build.json').write_text(json.dumps(record,indent=2)+'\n');print(json.dumps(record))
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Port reviewed private index modules into a default-limit distribution candidate.

Writes only its explicit files; it never edits routing, entry, registry, UI or manifests.
The optional --check compares bytes without writing. A fixed combined bundle is required.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'development/vr180'
SUPPORT = Path(__file__).with_name('indexed-runtime-support')
PINNED = {
    'index-prototype/index-store.mjs': 'a9d6c420e8acd894a0a657120c9f78765766c698103cf52bd18b7793472d0e7d',
    'index-prototype/job-owner.mjs': '8abfa8351570aefeed8a075a5848ea10130a057c5760a126914c82476f371447',
    'input-index-prototype/input-index.mjs': 'ff6f826e7b16b61283d736c4996e6feb8297a35eece311802aee4e8ef57e2e1b',
    'input-index-prototype/presentation-index.mjs': 'da4c9c11aae35a5efb07771f7734304879fd0fe9673179809c0360fe5205f55b',
    'output-index-prototype/output-index.mjs': 'baac33b77abebf388f030dd351c96669f7eb69ea100fde6503c04c16178b919f',
    'output-index-prototype/mp4-output-inspect.mjs': 'd841bab27d299316a890f8b16c628ed486ea803982269293f3faf10fe66ef229',
    'indexed-transform-prototype/transform.mjs': 'd53c648a4fdebe45b33d5d6890d3684bec8a89de1757e0bb477f202753071d0c',
}
BUNDLE_SHA = '65a96894f5442fe92d3672e09b80e6841b7a30a745b002b071636352f5b790cd'
sha = lambda value: hashlib.sha256(value).hexdigest()
encode = lambda value: (json.dumps(value, indent=2) + '\n').encode()


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise RuntimeError(f'Expected one reviewed context: {old[:100]}')
    return source.replace(old, new)


def port(name, source):
    # Imports alone move the existing index/geometry/AAC/codec calculations.
    for prefix in ['../index-prototype/', '../input-index-prototype/', '../output-index-prototype/']:
        source = source.replace("from '" + prefix, "from './")
    source = source.replace("from '../../../docs/shared/vr180/", "from '../")
    if name == 'index-store.mjs':
        source = replace_once(source, '// Non-public prototype. No product import, muxer/demuxer integration or recovery.',
                              '// Bounded disk index storage; ownership and recovery are handled by job-owner.mjs.')
    elif name == 'job-owner.mjs':
        source = replace_once(source, '// Private index jobs only. This is cooperative ownership, not an origin security boundary.',
                              '// Cooperative ownership for indexed jobs, not an origin security boundary.')
    elif name == 'input-index.mjs':
        source = replace_once(source, "import {inspectMp4 as inspectFixedMuxerFixture} from './mp4-output-inspect.mjs';\n", '')
        source = replace_once(source, ', fixedMuxerFixture = false, ownerToken', ', ownerToken')
        source = replace_once(source, " || typeof fixedMuxerFixture !== 'boolean'", '')
        source = replace_once(source,
            '      // Private fixture compatibility is explicit. Production/default admission\n'
            '      // always uses the unchanged public parser, including its cslg rejection.\n'
            '      inspection = await (fixedMuxerFixture ? inspectFixedMuxerFixture : inspectPublicMp4)(inspectedSource, {signal});',
            '      // Input admission always uses the unchanged strict parser, including cslg rejection.\n'
            '      inspection = await inspectPublicMp4(inspectedSource, {signal});')
        source = replace_once(source, "fixedMuxerFixture ? 'fixed-muxer-fixture-only' : 'unchanged-public-parser'", "'unchanged-public-parser'")
        source = source.replace('VR180 private asynchronous input-index prototype', 'VR180 bounded asynchronous input index')
        source = source.replace('One explicit private fork Input', 'One explicit combined-fork Input')
    elif name == 'output-index.mjs':
        source = source.replace('VR180 private bounded disk-index / incremental metadata prototype', 'VR180 bounded disk index / incremental metadata')
        source = replace_once(source, '// VR180 private prototype. Fixed upstream adapter; never imported by the public product.',
                              '// Fixed upstream adapter for the dedicated VR180 combined fork.')
    elif name == 'mp4-output-inspect.mjs':
        source = replace_once(source, '// PRIVATE OUTPUT-ONLY PARSER VARIANT. Generated by make-private-parser.py; public parser remains unchanged.',
                              '// OUTPUT-ONLY PARSER VARIANT. Input admission uses the unchanged strict ../mp4.mjs.')
    elif name == 'transform.mjs':
        source = replace_once(source,
            '// Private indexed pixel-conversion prototype; generated from the public transform.\n'
            '// Public/default limits stay unchanged; named private output profiles are explicit trial options.',
            '// Indexed direct-file conversion candidate; generated from reviewed prototype sources.\n'
            '// Only the existing default 1 GiB output profile is accepted.')
        source = replace_once(source, "  'p5-5gb': Object.freeze({id: 'p5-5gb', maxBytes: 5_200_000_000}),\n", '')
        source = replace_once(source, "  'p5-10gb': Object.freeze({id: 'p5-10gb', maxBytes: 10_200_000_000}),\n", '')
        source = source.replace('PRIVATE_OUTPUT_PROFILES', 'OUTPUT_PROFILES').replace('resolvePrivateOutputProfile', 'resolveOutputProfile')
        source = source.replace('PRIVATE_OUTPUT_PROFILE_UNSUPPORTED', 'OUTPUT_PROFILE_UNSUPPORTED')
        source = replace_once(source,
            "outputProfile.id === 'default' ? 'Experimental output limit: 1 GiB; invalid or oversized write.' : 'Private output limit: ' + outputProfile.id + ' ' + outputProfile.maxBytes + ' bytes; invalid or oversized write.'",
            "'Experimental output limit: 1 GiB; invalid or oversized write.'")
        source = source.replace('Private direct-file pixel route.', 'Indexed direct-file pixel route.')
        source = source.replace('Private jobId must contain', 'Indexed jobId must contain')
        source = source.replace('private bounded disk input/output indices; unchanged sample/metadata limits; explicit private output profile',
                                'bounded disk input/output indices; unchanged default sample/metadata/output limits')
        source = source.replace("'private-indexed-direct-file'", "'indexed-direct-file'")
    for forbidden in ['development/', 'fixedMuxerFixture', 'inspectFixedMuxerFixture', 'p5-5gb', 'p5-10gb']:
        if forbidden in source:
            raise RuntimeError(f'Private runtime dependency or opt-in remains: {name}: {forbidden}')
    return source


def prepare(bundle):
    files, derived = {}, {}
    for relative, expected in PINNED.items():
        raw = (SOURCE / relative).read_bytes()
        if sha(raw) != expected:
            raise RuntimeError(f'Prototype changed; review before porting: {relative}')
        name = Path(relative).name
        target = f'indexed/{name}'
        files[target] = port(name, raw.decode()).encode()
        derived[name] = {'source': f'development/vr180/{relative}', 'sourceSha256': expected, 'sha256': sha(files[target])}
    files['indexed/README.md'] = (SUPPORT / 'runtime-README.md').read_bytes()
    files['indexed/provenance.json'] = encode({'schemaVersion': 1, 'generator': 'tools/vr180/prepare-indexed-runtime.py',
        'outputProfiles': {'default': 1073741824}, 'inputAdmission': 'unchanged strict ../mp4.mjs; no fixture opt-in',
        'changes': ['relative imports', 'remove private input parser opt-in', 'default output cap only', 'distribution descriptions'],
        'runtime': derived})
    inputs = json.loads((SOURCE / 'build-inputs/provenance.json').read_text())
    bundle_bytes = bundle.read_bytes()
    if sha(bundle_bytes) != BUNDLE_SHA:
        raise RuntimeError('Fixed combined bundle SHA mismatch')
    files['vendor/mediabunny-indexed.mjs'] = bundle_bytes
    for target, origin, expected in [
        ('mediabunny-1.61.5-source.tgz', inputs['sourceArchive']['path'], inputs['sourceArchive']['sha256']),
        ('mediabunny-LICENSE', inputs['licensePath'], inputs['licenseSha256']),
    ]:
        raw = (ROOT / origin).read_bytes()
        if sha(raw) != expected:
            raise RuntimeError(f'Fixed upstream file changed: {origin}')
        files[f'vendor/{target}'] = raw
    patches = []
    for kind in ['output', 'input']:
        directory = SOURCE / f'{kind}-index-prototype'
        proof = json.loads((directory / 'patch-provenance.json').read_text())
        patch = (directory / f'mediabunny-{kind}-index.patch').read_bytes()
        if sha(patch) != proof['patchSha256']:
            raise RuntimeError(f'{kind} patch hash mismatch')
        path = f'mediabunny-{kind}-index.patch'
        files[f'vendor/{path}'] = patch
        patches.append({'path': path, **proof})
    recovered = []
    for item in inputs['recoveredFiles']:
        path = item['path']
        raw = (SOURCE / 'build-inputs/mediabunny-1.61.5' / path).read_bytes()
        if sha(raw) != item['sha256']:
            raise RuntimeError(f'Recovered source hash mismatch: {path}')
        files[f'vendor/source-supplement/{path}'] = raw
        recovered.append(item)
    for name in ['package.json', 'package-lock.json']:
        files[f'vendor/toolchain/{name}'] = (SOURCE / 'build-inputs/toolchain' / name).read_bytes()
    files['vendor/rebuild-indexed.mjs'] = (SUPPORT / 'rebuild-indexed.mjs').read_bytes()
    files['vendor/README.md'] = (SUPPORT / 'vendor-README.md').read_bytes()
    files['vendor/provenance.json'] = encode({
        'schemaVersion': 1, 'package': 'mediabunny', 'version': '1.61.5', 'upstreamRepository': inputs['upstreamRepository'],
        'upstreamCommit': inputs['upstreamCommit'], 'license': 'MPL-2.0', 'licensePath': 'mediabunny-LICENSE',
        'modifications': 'Output and input disk-index hooks; apply listed patches in order. Runtime controller source is in ../indexed/.',
        'sourceArchive': {**inputs['sourceArchive'], 'path': 'mediabunny-1.61.5-source.tgz'},
        'unmodifiedBundleSha256': inputs['expectedBundle']['sha256'],
        'bundle': {'path': 'mediabunny-indexed.mjs', 'sha256': BUNDLE_SHA, 'bytes': len(bundle_bytes)},
        'patches': patches, 'sourceSupplement': recovered,
        'toolchain': {'esbuildVersion': '0.25.1', 'package': 'toolchain/package.json', 'lock': 'toolchain/package-lock.json',
                      'installationPolicy': inputs['toolchain']['installationPolicy']},
        'buildOptionsSource': inputs['buildOptionsSource'],
        'files': {key.removeprefix('vendor/'): {'sha256': sha(value), 'bytes': len(value)}
                  for key, value in files.items() if key.startswith('vendor/')},
    })
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, default=ROOT / 'docs/shared/vr180/vendor/mediabunny-indexed.mjs')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'docs/shared/vr180')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = prepare(args.bundle)
    for relative, raw in files.items():
        target = args.output_dir / relative
        if args.check:
            if not target.is_file() or target.read_bytes() != raw:
                raise RuntimeError(f'Distribution differs: {relative}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    print(json.dumps({'status': 'PASS', 'checkOnly': args.check, 'files': len(files),
                      'bytes': sum(map(len, files.values())), 'bundleSha256': BUNDLE_SHA}))


if __name__ == '__main__':
    main()

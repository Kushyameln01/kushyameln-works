import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {readUnityPackage} from '../../docs/shared/ft/unity-package.mjs';
import {parseExpression} from '../../docs/animator-composer/lib/registration.mjs';
import {extractAnimatorParameters,splitUnityDocuments} from '../../docs/shared/ft/unity-text.mjs';
const expected=['AlwaysOne','Function/Test','Proxy/Smooth/Parts','Proxy/Test/Cartesian','Proxy/Test/Output','Smooth/Test','Smooth/Test_Function','v2/Test','v2/Test0','v2/Test1','v2/Test2','v2/Test4','v2/Test8','v2/TestNegative'].sort();
const input=process.argv[2];if(!input)throw Error('Provide actual browser-downloaded package path');
const assets=[...readUnityPackage(await readFile(input)).values()];
assert.equal(assets.length,3);assert.equal(assets.filter(a=>a.asset===null).length,1);
const decoder=new TextDecoder();
const c=decoder.decode(assets.find(a=>a.path.endsWith('.controller')).asset);
const e=parseExpression(decoder.decode(assets.find(a=>a.path.endsWith('.asset')).asset));
assert.deepEqual(extractAnimatorParameters(c).map(p=>p.name),expected);
assert.deepEqual(e.map(p=>p.name),expected);
assert(e.every(p=>p.type==='Float'&&p.defaultValue===.25&&p.saved&&p.networkSynced));
assert(extractAnimatorParameters(c).every(p=>p.fields.m_Type==='1'&&p.fields.m_DefaultFloat==='0.25'));
assert.deepEqual(splitUnityDocuments(c).documents.map(d=>d.classId),['91','1107']);
assert(!assets.some(a=>/report|\.json$/i.test(a.path)));
console.log('PASS actual browser download: 14 exact Parameters, settings, minimal Controller + Expression + folder, no report.');

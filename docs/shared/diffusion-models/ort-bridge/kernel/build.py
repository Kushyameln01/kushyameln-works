#!/usr/bin/env python3
"""Rebuild the bounded bridge with the pinned private Hike/WABT toolchain."""
import hashlib,json,os,re,subprocess
from pathlib import Path
r=Path(__file__).resolve().parent
t=Path(os.environ.get('DIFFUSION_TOOLCHAIN',str(r.parents[2]/'toolchain'))).resolve()
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
provenance=json.loads((t/'provenance.json').read_text())
if provenance['hikeCommit']!='3c51fde6675f317453919bd505d0e2d0f638e7f1':raise RuntimeError('Unexpected compiler commit')
if sha(t/'hikec')!=provenance['sha256']['compiler']:raise RuntimeError('Compiler hash differs')
env=dict(os.environ,PATH=str(t/'wabt/node_modules/.bin')+os.pathsep+os.environ['PATH'])
command=[str(t/'hikec'),'build','-target','wabt','-wasm-mode','normal','-o',str(r/'bridge.wasm'),str(r/'bridge.hike')]
p=subprocess.run(command,env=env,capture_output=True,text=True)
(r/'build.log').write_text(p.stdout+p.stderr);p.check_returncode()
subprocess.run(['node',str(t/'wabt/node_modules/wabt/bin/wasm2wat'),str(r/'bridge.wasm'),'-o',str(r/'bridge.wat')],check=True)
wat=(r/'bridge.wat').read_text()
if '(import ' in wat:raise RuntimeError('Unexpected imports')
signatures={'DequantScale':'i32 i32 f32 i32 i32','AddBias':'i32 i32 i32 i32 i32'}
for name,signature in signatures.items():
    idx=re.search(r'\(export "'+name+r'" \(func (\d+)\)\)',wat).group(1)
    pattern=r'\(func \(;'+idx+r';\) \(type \d+\) \(param '+signature+r'\) \(result i32\)'
    if not re.search(pattern,wat):raise RuntimeError('Unexpected ABI: '+name)
digest=sha(r/'bridge.wasm')
(r/'registry.mjs').write_text('// Generated by build.py; pair this registry with its WASM.\nexport const BRIDGE_WASM_SHA256='+json.dumps(digest)+';\n')
record={'hikeCommit':provenance['hikeCommit'],'compilerSha256':sha(t/'hikec'),'backend':'wabt','mode':'normal','flags':['-target','wabt','-wasm-mode','normal'],'sourceSha256':sha(r/'bridge.hike'),'wasmSha256':digest,'watSha256':sha(r/'bridge.wat'),'runtimeSha256':sha(r/'runtime.js'),'versions':provenance['versions'],'command':command,'imports':[],'abi':signatures,'status':'BUILT_ABI_INSPECTED; runtime evidence in node-results.json'}
(r/'build-record.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps(record))

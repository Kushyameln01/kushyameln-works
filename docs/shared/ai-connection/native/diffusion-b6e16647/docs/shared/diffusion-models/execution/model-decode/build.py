#!/usr/bin/env python3
"""Build the lookup-only decoder using the pinned private offline Hike compiler."""
import hashlib
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TOOLCHAIN = Path(os.environ["DIFFUSION_TOOLCHAIN"]).resolve()
sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
provenance = json.loads((TOOLCHAIN / "provenance.json").read_text())
if provenance["hikeCommit"] != "3c51fde6675f317453919bd505d0e2d0f638e7f1":
    raise RuntimeError("Unexpected Hike compiler commit")
if sha(TOOLCHAIN / "hikec") != "fb4588cba306b8dded91ad02735254681eaca08fa997f55919185cd607e89b26" or sha(TOOLCHAIN / "hikec") != provenance["sha256"]["compiler"]:
    raise RuntimeError("Compiler hash differs")
environment = dict(os.environ, PATH=str(TOOLCHAIN / "wabt/node_modules/.bin") + os.pathsep + os.environ["PATH"])
command = [str(TOOLCHAIN / "hikec"), "build", "-target", "wabt", "-wasm-mode", "normal", "-o", str(ROOT / "model-decode.wasm"), str(ROOT / "model-decode.hike")]
process = subprocess.run(command, env=environment, capture_output=True, text=True)
(ROOT / "build.log").write_text(process.stdout + process.stderr)
process.check_returncode()
subprocess.run(["node", str(TOOLCHAIN / "wabt/node_modules/wabt/bin/wasm2wat"), str(ROOT / "model-decode.wasm"), "-o", str(ROOT / "model-decode.wat")], check=True)
wat = (ROOT / "model-decode.wat").read_text()
if "(import " in wat:
    raise RuntimeError("Unexpected WASM imports")
if re.search(r"\bf32\.(add|sub|mul|div)\b", wat):
    raise RuntimeError("Lookup decoder must copy oracle values without floating point arithmetic")
signatures = {"Lookup8": "i32 i32 i32 i32 i32", "Lookup16": "i32 i32 i32 i32 i32"}
for name, signature in signatures.items():
    index = re.search(r'\(export "' + name + r'" \(func (\d+)\)\)', wat).group(1)
    if not re.search(r'\(func \(;' + index + r';\) \(type \d+\) \(param ' + signature + r'\) \(result i32\)', wat):
        raise RuntimeError("Unexpected ABI: " + name)
digest = sha(ROOT / "model-decode.wasm")
(ROOT / "registry.mjs").write_text('// Generated by build.py; pair this registry with its WASM.\nexport const MODEL_DECODE_WASM_SHA256=' + json.dumps(digest) + ';\n')
record = {"hikeCommit": provenance["hikeCommit"], "compilerSha256": sha(TOOLCHAIN / "hikec"), "backend": "wabt", "mode": "normal", "sourceSha256": sha(ROOT / "model-decode.hike"), "hostSha256": sha(ROOT.parent / "model-decode.mjs"), "builderSha256": sha(Path(__file__)), "wasmSha256": digest, "watSha256": sha(ROOT / "model-decode.wat"), "runtimeSha256": sha(ROOT / "runtime.js"), "versions": provenance["versions"], "command": command, "imports": [], "abi": signatures, "status": "BUILT_ABI_INSPECTED; exhaustive runtime tests in test-model-decode.mjs"}
(ROOT / "build-record.json").write_text(json.dumps(record, indent=2) + "\n")
print(json.dumps(record))

"""Build the general rows1..128 model math ABI with the pinned Hike compiler."""
import hashlib,json,os,re,subprocess
from pathlib import Path
r=Path(__file__).resolve().parent
t=Path(os.environ['DIFFUSION_TOOLCHAIN']).resolve()
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
p=json.loads((t/'provenance.json').read_text())
assert p['hikeCommit']=='3c51fde6675f317453919bd505d0e2d0f638e7f1'
assert sha(t/'hikec')=='fb4588cba306b8dded91ad02735254681eaca08fa997f55919185cd607e89b26'
command=[str(t/'hikec'),'build','-target','wabt','-wasm-mode','normal','-o',str(r/'kernel.wasm'),str(r/'math.hike')]
env=dict(os.environ,PATH=str(t/'wabt/node_modules/.bin')+os.pathsep+os.environ['PATH'])
run=subprocess.run(command,env=env,capture_output=True,text=True)
(r/'build.log').write_text(run.stdout+run.stderr)
run.check_returncode()
runtime=r/'runtime.js'
runtime.write_text('\n'.join(line.rstrip() for line in runtime.read_text().splitlines()).rstrip()+'\n')
subprocess.run(['node',str(t/'wabt/node_modules/wabt/bin/wasm2wat'),str(r/'kernel.wasm'),'-o',str(r/'kernel.wat')],check=True)
wat=(r/'kernel.wat').read_text()
imports={'cos':'f64','sin':'f64','pow':'f64 f64','sqrt':'f64','tanh':'f64','exp':'f64'}
assert set(re.findall(r'\(import "env" "([^"]+)"',wat))==set(imports)
for name,signature in imports.items():
 m=re.search(r'\(import "env" "'+name+r'" \(func \(;\d+;\) \(type (\d+)\)\)\)',wat)
 assert m,name
 assert re.search(r'\(type \(;'+m[1]+r';\) \(func \(param '+signature+r'\) \(result f64\)\)\)',wat),name
abi={
 'Norm':'i32 i32 i32 i32 i32 i32 i32',
 'Modulate':'i32 i32 i32 i32 i32 i32',
 'GateResidual':'i32 i32 i32 i32 i32 i32',
 'Add':'i32 i32 i32 i32 i32',
 'Gelu':'i32 i32 i32 i32',
 'Silu':'i32 i32 i32 i32',
 'Bias':'i32 i32 i32 i32 i32 i32 i32',
 'DivideAttention':'i32 i32 i32 i32 i32 i32 i32 i32 i32',
 'Sinusoidal':'f32 i32 i32',
 'RopeBuild':'i32 i32 i32 i32 i32',
 'RopeApply':'i32 i32 i32 i32 i32',
}
for name,signature in abi.items():
 idx=re.search(r'\(export "'+name+r'" \(func (\d+)\)\)',wat)[1]
 assert re.search(r'\(func \(;'+idx+r';\) \(type \d+\) \(param '+signature+r'\) \(result i32\)',wat),name
assert 'f32.mul' in wat and 'f32.add' in wat and 'f32.div' in wat
h=sha(r/'kernel.wasm')
(r/'registry.mjs').write_text('// Generated by model-math/build.py\nexport const MODEL_MATH_WASM_SHA256='+json.dumps(h)+';\n')
host=r.parent/'model-math.mjs'
record={'hikeCommit':p['hikeCommit'],'compilerSha256':sha(t/'hikec'),'backend':'wabt','mode':'normal','sourceSha256':sha(r/'math.hike'),'sourceBytes':(r/'math.hike').stat().st_size,'hostSha256':sha(host),'hostBytes':host.stat().st_size,'builderSha256':sha(Path(__file__)),'wasmSha256':h,'wasmBytes':(r/'kernel.wasm').stat().st_size,'watSha256':sha(r/'kernel.wat'),'runtimeSha256':sha(runtime),'imports':[{'module':'env','name':name,'signature':signature+' -> f64','bridge':'fixed ECMAScript Math.'+name} for name,signature in imports.items()],'abi':abi,'command':command,'versions':p['versions'],'limits':{'queryRows':128,'featureWidth':5120,'headWidth':128,'heads':40,'unaryChunkElements':81920,'linearWidth':13824},'attentionDivisionProfile':'F32 division; head-major[40,Q,128] / finite-positive denominator[40,Q]; Q1..128 exact tails; chunk<=81920, native offset+count bounds','scope':'general synchronous D1 F32 model math and D2 attention denominator division; full5120 norms and token-major all40heads RoPE, rows1..128 exact tails; fixed scalar transcendentals; not complete model or GPU precision parity'}
(r/'build-record.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps({'wasmSha256':h,'bytes':(r/'kernel.wasm').stat().st_size}))

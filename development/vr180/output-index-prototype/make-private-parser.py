#!/usr/bin/env python3
"""Regenerate the output-only parser variant; never modifies the public parser."""
from pathlib import Path
import hashlib,json,difflib
here=Path(__file__).parent
source=here.parents[2]/'docs/shared/vr180/mp4.mjs'
original=source.read_text();s=original
s=s.replace("stbl: new Set(['stsd', 'stts', 'ctts',", "stbl: new Set(['stsd', 'stts', 'ctts', 'cslg',",1)
s=s.replace('let decodeRuns, compositionRuns = null;', 'let decodeRuns, compositionRuns = null, leastOffset = Infinity, greatestOffset = -Infinity;',1)
s=s.replace("if (type === 'stts') check(d.getUint32(4) > 0, 'zero-duration samples are unsupported');", """if (type === 'stts') check(d.getUint32(4) > 0, 'zero-duration samples are unsupported');
      else { const offset = table.version ? d.getInt32(4) : d.getUint32(4); leastOffset = Math.min(leastOffset, offset); greatestOffset = Math.max(greatestOffset, offset); }""",1)
s=s.replace('  return { minPts, maxEnd, samples };', '''  // Private OUTPUT-only extension for the pinned generator's version-0 signed
  // cslg summary. All five values must agree with the completely scanned tables.
  // This does not enable arbitrary cslg/QuickTime inputs in the public product.
  const cslg = one(stbl, 'cslg', false);
  if (cslg) {
    const d = full(cslg, [0], 24, true);
    check(d.byteLength === 24, 'invalid cslg payload size');
    check(compositionRuns?.version === 1, 'private cslg requires signed ctts version 1');
    const expected = [Math.max(-leastOffset, 0), leastOffset, greatestOffset, minPts, maxEnd];
    for (let i = 0; i < expected.length; i++) {
      check(Number.isInteger(expected[i]) && expected[i] >= -2147483648 && expected[i] <= 2147483647
        && d.getInt32(4 + i * 4) === expected[i], 'cslg summary disagrees with complete timing tables');
    }
  }
  return { minPts, maxEnd, samples };''',1)
if s==original:raise RuntimeError('No patch applied')
header='// PRIVATE OUTPUT-ONLY PARSER VARIANT. Generated by make-private-parser.py; public parser remains unchanged.\n'
(here/'mp4-output-inspect.mjs').write_text(header+s)
patch=''.join(difflib.unified_diff(original.splitlines(True),(header+s).splitlines(True),fromfile='a/docs/shared/vr180/mp4.mjs',tofile='b/development/vr180/output-index-prototype/mp4-output-inspect.mjs'))
(here/'mp4-output-inspect.patch').write_text(patch)
(here/'parser-provenance.json').write_text(json.dumps({'source':'docs/shared/vr180/mp4.mjs','sourceSha256':hashlib.sha256(original.encode()).hexdigest(),
 'privateSha256':hashlib.sha256((header+s).encode()).hexdigest(),'patchSha256':hashlib.sha256(patch.encode()).hexdigest(),
 'scope':'Output-only pinned version-0 signed cslg + signed ctts; no public input acceptance change',
 'reason':'Unmodified fixed Mediabunny alternating-ctts output is rejected by the public parser because cslg is not permitted.',
 'references':['https://mp4ra.org/registered-types/boxes','https://developer.apple.com/documentation/quicktime-file-format/composition_shift_least_greatest_atom',
 'https://github.com/Vanilagy/mediabunny/blob/0664a57bf2f40e5c4efa176c75ebf1d60df69eb8/src/isobmff/isobmff-boxes.ts#L1320'],
 'semanticScope':'MP4RA identifies the ISO box; Apple documents the summary fields. Exact signed-field and positive shift interpretation here is the pinned ISO generator contract, not generic QuickTime ctts semantics.'},indent=2)+'\n')
